local currentZones = {}
local isActive = false
local startTime = 0 

function GetRandomZones()
    local picked = {}
    local count = 1
    
    if #Config.Zones < count then count = #Config.Zones end

    while #picked < count do
        local index = math.random(1, #Config.Zones)
        local alreadyPicked = false
        for _, v in ipairs(picked) do
            if v == index then alreadyPicked = true break end
        end
        if not alreadyPicked then
            table.insert(picked, index)
        end
    end

    local finalZones = {}
    for _, index in ipairs(picked) do
        table.insert(finalZones, Config.Zones[index])
    end
    return finalZones
end

Citizen.CreateThread(function()
    while true do
        isActive = false
        currentZones = {}
        TriggerClientEvent('t1software:deactivate', -1)
        Citizen.Wait(Config.CooldownDuration)

        currentZones = GetRandomZones()
        isActive = true
        startTime = os.time()
        TriggerClientEvent('t1software:activate', -1, currentZones)

        Citizen.Wait(Config.ActiveDuration)
    end
end)

exports('GetTrapData', function()
    if not isActive then return "None", 0 end
    
    local names = ""
    for i, zone in ipairs(currentZones) do
        names = names .. zone.name .. (i < #currentZones and " & " or "")
    end

    -- Calculate remaining seconds
    local elapsed = os.time() - startTime
    local remaining = (Config.ActiveDuration / 1000) - elapsed
    
    return names, math.max(0, math.floor(remaining))
end)

RegisterNetEvent('esx:playerLoaded')
AddEventHandler('esx:playerLoaded', function(source)
    if isActive and #currentZones > 0 then
        TriggerClientEvent('t1software:activate', source, currentZones)
    end
end)

